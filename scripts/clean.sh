#!/usr/bin/env bash
# Reclaim disk from build artifacts — everything this removes is regenerated
# by a build. No source, no config, no git history is ever touched.
#
#   ./scripts/clean.sh                  report only: what exists and how big
#   ./scripts/clean.sh --stale          reap artifacts unused for 7+ days  ← routine
#   ./scripts/clean.sh --stale 3        …or a different age in days
#   ./scripts/clean.sh --cache          incremental compile caches only
#   ./scripts/clean.sh --build          all cargo output (target/)
#   ./scripts/clean.sh --all            + node_modules, dist, test-server state
#   ./scripts/clean.sh --scratch        the out-of-repo kernel-build cache
#   ./scripts/clean.sh --everything     --all plus --scratch
#
#   --yes / -y    skip the confirmation prompt (required when non-interactive)
#
# Which one do you want?
#
#   Reclaiming space day to day .... --stale
#       Cargo never garbage-collects: every rebuild after an edit writes a new
#       hash-suffixed binary and orphans the old one forever. That is what
#       grows target/ to tens of GB — this repo hit 249 test binaries where
#       ~40 were current, 32.8 GB of pure garbage. --stale reaps exactly that
#       while leaving recent builds warm, so it is cheap to run often.
#
#   Backing up or archiving the repo ... --all
#       Strips the tree to what belongs in an archive. Restore with a build.
#
#   Freeing the most space, right now .. --everything
#
# Nothing here needs sudo, and nothing runs if a build is in progress.

set -euo pipefail

# pwd -P, not pwd: the guard in remove_paths compares against `readlink -f`
# output, so ROOT must be symlink-resolved too or every path looks "outside
# the repo" when the tree is reached through a symlinked parent directory.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$ROOT"

# Guard: never operate on a tree that is not this project.
[[ -f "$ROOT/Cargo.toml" && -d "$ROOT/crates" ]] \
  || { echo "error: $ROOT does not look like the meshware repo" >&2; exit 1; }

# Out-of-repo scratch dir used by examples/test-git-repo/seed/scripts/kernel-build.sh
KBUILD_DIR="${MESHWARE_KBUILD_DIR:-/var/tmp/meshware-kbuild}"
# Canonical form of the same dir, for that guard (/var/tmp is a symlink on
# some systems, and MESHWARE_KBUILD_DIR may point through one).
KBUILD_REAL="$(readlink -f "$KBUILD_DIR" 2>/dev/null || printf '%s' "$KBUILD_DIR")"

MODE=report
STALE_DAYS=7
ASSUME_YES=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --stale)      MODE=stale
                  [[ "${2:-}" =~ ^[0-9]+$ ]] && { STALE_DAYS="$2"; shift; }
                  shift ;;
    --cache)      MODE=cache;      shift ;;
    --build)      MODE=build;      shift ;;
    --all)        MODE=all;        shift ;;
    --scratch)    MODE=scratch;    shift ;;
    --everything) MODE=everything; shift ;;
    --yes|-y)     ASSUME_YES=true; shift ;;
    --help|-h)    awk 'NR>1 && /^#/ { sub(/^# ?/, ""); print; next } NR>1 { exit }' "$0"; exit 0 ;;
    *)            echo "error: unknown option '$1' (try --help)" >&2; exit 1 ;;
  esac
done

# ---------------------------------------------------------------------------
bold() { printf '\033[1m%s\033[0m' "$*"; }
dim()  { printf '\033[2m%s\033[0m' "$*"; }

bytes_of() { # <path> → size in bytes, 0 if absent
  [[ -e "$1" ]] || { echo 0; return; }
  du -sb "$1" 2>/dev/null | cut -f1 || echo 0
}
human() { numfmt --to=iec --suffix=B "${1:-0}" 2>/dev/null || printf '%s' "${1:-0}"; }
free_bytes() { df -PB1 "$ROOT" | awk 'NR==2{print $4}'; }

# Refuse to pull the rug out from under a running build.
if pgrep -x cargo >/dev/null 2>&1 || pgrep -x rustc >/dev/null 2>&1; then
  echo "error: a cargo/rustc build is running — wait for it to finish" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# The inventory. Every entry is a fixed, literal path under $ROOT (or the
# kernel scratch dir) — never anything derived from user input.
# ---------------------------------------------------------------------------
#            key|path|group|what it is|how to get it back
ITEMS=(
  "cargo|target|build|Rust build output, all profiles|cargo build --workspace"
  "tauri|apps/director/src-tauri/target|build|Tauri build output|scripts/director.sh"
  "node|apps/director/node_modules|extra|npm dependencies|cd apps/director && npm install"
  "dist|apps/director/dist|extra|Director frontend build|cd apps/director && npm run build"
  "testrepo|examples/test-git-repo/.run|extra|sample Git server state|examples/test-git-repo/serve.sh"
  "kbuild|${KBUILD_DIR}|scratch|kernel-build scratch (outside the repo)|re-downloads on next run"
)

report() {
  local total=0 shown=0 key path group what regen size
  printf '\n%s\n\n' "$(bold "build artifacts under $ROOT")"
  printf '  %-34s %10s   %s\n' "PATH" "SIZE" "REGENERATED BY"
  printf '  %-34s %10s   %s\n' "$(printf '─%.0s' {1..34})" "──────────" "$(printf '─%.0s' {1..30})"
  for entry in "${ITEMS[@]}"; do
    IFS='|' read -r key path group what regen <<<"$entry"
    size=$(bytes_of "$path")
    (( size == 0 )) && continue
    shown=$((shown + 1)); total=$((total + size))
    printf '  %-34s %10s   %s\n' "$path" "$(human "$size")" "$regen"
  done
  (( shown == 0 )) && printf '  %s\n' "$(dim "nothing to clean — the tree is already bare")"
  # Format first, then bold: ANSI codes would otherwise be counted as
  # characters by printf's field width and skew the column.
  printf '\n%s\n' "$(bold "$(printf '  %-34s %10s' total "$(human "$total")")")"

  # The stale slice, called out separately: this is the number that matters
  # for routine cleanup.
  if [[ -d target ]]; then
    local stale
    stale=$(stale_bytes)
    printf '\n  %s\n' "$(dim "of which unused for ${STALE_DAYS}+ days: $(human "$stale")  → ./scripts/clean.sh --stale")"
  fi
  printf '\n  %s\n\n' "$(dim "free on this filesystem: $(human "$(free_bytes)")")"
}

# Cargo's intermediate dirs — where essentially all the bloat lives. Final
# output binaries at the top of each profile dir are deliberately left alone.
intermediate_dirs() {
  local d
  for d in target/*/deps target/*/.fingerprint target/*/build target/*/incremental \
           target/*/*/deps target/*/*/.fingerprint target/*/*/build target/*/*/incremental \
           apps/director/src-tauri/target/*/deps apps/director/src-tauri/target/*/incremental; do
    [[ -d "$d" ]] && printf '%s\n' "$d"
  done
  return 0
}

stale_bytes() {
  local total=0 d n
  while read -r d; do
    [[ -n "$d" ]] || continue
    n=$(find "$d" -type f -mtime +"$STALE_DAYS" -printf '%s\n' 2>/dev/null | awk '{s+=$1} END{print s+0}')
    total=$((total + n))
  done < <(intermediate_dirs)
  echo "$total"
}

cache_dirs() {
  local d
  for d in target/*/incremental target/*/*/incremental \
           apps/director/src-tauri/target/*/incremental; do
    [[ -d "$d" ]] && printf '%s\n' "$d"
  done
  return 0
}

confirm() { # <what>
  $ASSUME_YES && return 0
  if [[ ! -t 0 ]]; then
    echo "error: not interactive — pass --yes to confirm" >&2
    exit 1
  fi
  printf '\n%s ' "$(bold "Remove $1?") [y/N]"
  local reply; read -r reply
  [[ "$reply" == [yY] || "$reply" == [yY][eE][sS] ]] || { echo "aborted."; exit 0; }
}

RECLAIMED=0

remove_paths() { # reads paths on stdin
  local p sz
  while read -r p; do
    [[ -n "$p" && -e "$p" ]] || continue
    # Belt and braces: only ever inside $ROOT or the kernel scratch dir.
    case "$(readlink -f "$p")" in
      "$ROOT"/*|"$KBUILD_REAL"|"$KBUILD_REAL"/*) ;;
      *) echo "  refusing to touch $p (outside the repo)" >&2; continue ;;
    esac
    sz=$(bytes_of "$p")
    printf '  removing %s %s\n' "$p" "$(dim "($(human "$sz"))")"
    rm -rf -- "$p"
    RECLAIMED=$((RECLAIMED + sz))
  done
}

group_paths() { # <group>[ <group>…]
  local want entry key path group what regen
  for entry in "${ITEMS[@]}"; do
    IFS='|' read -r key path group what regen <<<"$entry"
    for want in "$@"; do
      [[ "$group" == "$want" && -e "$path" ]] && printf '%s\n' "$path"
    done
  done
  return 0
}

# ---------------------------------------------------------------------------
case "$MODE" in
  report)
    report
    cat <<EOF
  $(dim "Nothing was deleted. Pick a mode:")

    --stale        reap what has not been touched in ${STALE_DAYS}+ days $(dim "(routine)")
    --cache        drop incremental compile caches
    --build        drop all cargo output
    --all          drop everything regenerable in the repo $(dim "(before a backup)")
    --everything   --all plus the out-of-repo kernel cache

EOF
    exit 0 ;;

  stale)
    echo "==> reaping build artifacts unused for ${STALE_DAYS}+ days"
    reclaim=$(stale_bytes)
    if (( reclaim == 0 )); then
      echo "    nothing older than ${STALE_DAYS} days — already tidy"
      exit 0
    fi
    echo "    $(human "$reclaim") to reclaim across $(intermediate_dirs | wc -l) directories"
    confirm "$(human "$reclaim") of stale artifacts"
    RECLAIMED=$reclaim
    while read -r d; do
      [[ -n "$d" ]] || continue
      find "$d" -type f -mtime +"$STALE_DAYS" -delete 2>/dev/null || true
      find "$d" -mindepth 1 -type d -empty -delete 2>/dev/null || true
    done < <(intermediate_dirs)
    echo "    cargo will rebuild anything it still needs"
    ;;

  cache)
    mapfile -t caches < <(cache_dirs)
    if (( ${#caches[@]} == 0 )); then echo "no incremental caches present"; exit 0; fi
    total=0; for d in "${caches[@]}"; do total=$((total + $(bytes_of "$d"))); done
    echo "==> dropping incremental compile caches ($(human "$total"))"
    confirm "$(human "$total") of incremental cache"
    remove_paths < <(printf '%s\n' "${caches[@]}")
    echo "    next build is a normal build; only incremental speed is affected"
    ;;

  build)
    echo "==> dropping all cargo build output"
    confirm "all cargo build output"
    remove_paths < <(group_paths build)
    echo "    restore with: cargo build --workspace"
    ;;

  all)
    echo "==> dropping everything regenerable in the repo"
    confirm "all build output, node_modules, dist and test-server state"
    remove_paths < <(group_paths build extra)
    cat <<'EOF'
    restore with:
      cargo build --workspace
      cd apps/director && npm install && npm run build
EOF
    ;;

  scratch)
    if [[ ! -e "$KBUILD_DIR" ]]; then echo "no kernel-build scratch at $KBUILD_DIR"; exit 0; fi
    echo "==> dropping the kernel-build scratch dir ($(human "$(bytes_of "$KBUILD_DIR")"))"
    confirm "$KBUILD_DIR"
    remove_paths < <(group_paths scratch)
    ;;

  everything)
    echo "==> dropping everything regenerable, in the repo and out"
    confirm "all build output, node_modules, dist, test-server state and $KBUILD_DIR"
    remove_paths < <(group_paths build extra scratch)
    ;;
esac

printf '\n%s  %s reclaimed · %s free\n\n' \
  "$(bold done.)" "$(human "$RECLAIMED")" "$(human "$(free_bytes)")"
